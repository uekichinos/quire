/**
 * Advanced example — the "kitchen sink": the streaming writer, sheet/workbook
 * protection with one unlocked column, outline (grouping) with subtotal rows,
 * icon-set + top10 conditional formats, rich text, a comment, and
 * custom-formula data validation. Reads the result back to prove it all
 * round-trips.
 *
 * Run: node examples/3-advanced.mjs   (after `pnpm build`)
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { createStreamingWorkbook, readWorkbook } from '../dist/index.js'

const REGIONS = ['North', 'South', 'East', 'West']
const ROWS_PER_REGION = 500

const wb = createStreamingWorkbook()
const sheet = wb.addWorksheet('Inventory', {
  columns: [{ width: 16 }, { width: 12 }, { width: 12 }, { width: 10 }],
  freeze: { ySplit: 1 },
  outline: { summaryBelow: true },
})

// setColumn must run before the first addRow() in streaming mode — leave the
// Quantity column editable once the sheet is protected below
sheet.setColumn(3, { style: { protection: { locked: false } } })

sheet.addRow([
  [{ text: 'Inventory — ', font: { bold: true } }, { text: 'auto-generated demo', font: { italic: true } }],
  'Region',
  'Quantity',
  'Flag',
])

let grandTotal = 0
for (const region of REGIONS) {
  let subtotal = 0
  for (let i = 1; i <= ROWS_PER_REGION; i++) {
    const qty = Math.round(Math.random() * 500)
    subtotal += qty
    sheet.addRow([`SKU-${region}-${i}`, region, qty, qty % 2 === 0 ? 'even' : 'odd'], { outlineLevel: 1 })
  }
  grandTotal += subtotal
  sheet.addRow([`${region} subtotal`, '', subtotal, ''], {
    style: { font: { bold: true } },
    outlineLevel: 0,
  })
}

sheet.setDataValidation('C2:C3000', { type: 'custom', formula: 'C2>=0' })
sheet.addConditionalFormat('C2:C3000', { type: 'iconSet', iconSet: '3TrafficLights1' })
sheet.addConditionalFormat('C2:C3000', {
  type: 'top10',
  rank: 10,
  style: { fill: 'C6EFCE', font: { bold: true } },
})
sheet.setComment('A1', 'Generated by examples/3-advanced.mjs — safe to regenerate.', { author: 'quire' })

sheet.protect({ allowSort: true, allowAutoFilter: true })
wb.protect({ lockWindows: true })

const bytes = await wb.finish()

mkdirSync(new URL('./output/', import.meta.url), { recursive: true })
writeFileSync(new URL('./output/3-advanced.xlsx', import.meta.url), bytes)

// read it back and check the metadata that a hand-inspection of the .xlsx won't show at a glance
const back = readWorkbook(bytes, { styles: true })
const back_sheet = back.sheet('Inventory')
console.log('Rows written:', back_sheet.dimension.rows, '| grand total quantity:', grandTotal)
console.log('Data validations:', back_sheet.dataValidations.length)
console.log('Conditional formats:', back_sheet.conditionalFormats.map((c) => c.rule.type))
console.log('First detail row outline level:', back_sheet.rowInfo.get(2)?.outlineLevel)
// level 0 is Excel's own default and isn't written to the XML at all, so the
// subtotal row has no rowInfo entry — ?? 0 makes that default explicit here
console.log('First subtotal row outline level:', back_sheet.rowInfo.get(ROWS_PER_REGION + 2)?.outlineLevel ?? 0)
console.log('Sheet protection:', back_sheet.protection)
console.log('Workbook protection:', back.protection)
console.log('C2 unlocked?', back_sheet.cell('C2').style?.protection)
